# Exercício 2 — condicionais
# O mesmo teste aparece duas vezes de propósito.
# No exercício de funções ele vira uma função só.

numero = 17

if numero % 2 == 0:
    print(numero, "é par")
else:
    print(numero, "é ímpar")

outro_numero = 10

if outro_numero % 2 == 0:
    print(outro_numero, "é par")
else:
    print(outro_numero, "é ímpar")
