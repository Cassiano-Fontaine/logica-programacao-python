# Exercício 5 — comparar dois números
# Troque primeiro e segundo para cair em outro caso.

primeiro = 15
segundo = 22

print("Primeiro número:", primeiro)
print("Segundo número:", segundo)

if primeiro > segundo:
    print(primeiro, "é maior")
elif segundo > primeiro:
    print(segundo, "é maior")
else:
    print("Os dois números são iguais")
